const RTL_LANGUAGES: LanguageCode[] = ["ar"];

const STORAGE_KEY = "KILIMO-lang";

function detectLanguage(): LanguageCode {
  const stored = typeof window !== "undefined" ? window.localStorage.getItem(STORAGE_KEY) : null;
  if (stored && ["fr", "en", "sw", "ha", "yo", "ar", "ru", "zh", "de"].includes(stored)) return stored as LanguageCode;
  if (typeof navigator !== "undefined") {
    const nav = navigator.language?.toLowerCase() || "fr";
    const base = nav.split("-")[0];
    if (["fr", "en", "sw", "ha", "yo", "ar", "ru", "zh", "de"].includes(base)) return base as LanguageCode;
  }
  return "fr";
}

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<LanguageCode>(detectLanguage());

  const setLang = useCallback((next: LanguageCode) => {
    setLangState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch (e) {
      console.error("Failed to save language to localStorage:", e);
    }
  }, []);

  // Garde <html lang>/<html dir> synchronisés — nécessaire pour l'accessibilité,
  // le SEO, et pour que les langues RTL (arabe) s'affichent correctement.
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL_LANGUAGES.includes(lang) ? "rtl" : "ltr";
  }, [lang]);

  const t = useCallback(
    (key: string) => {
      const dict = resources[lang] || resources.fr;
      // Fallback à FR si la clé manque dans la langue courante
      return (dict[key] ?? resources.fr[key] ?? key);
    },
    [lang]
  );

  const available = useMemo<{
    code: LanguageCode;
    label: string;
  }[]>(() => (
    [
      { code: "fr" as LanguageCode, label: resources.fr["lang.name"] },
      { code: "en" as LanguageCode, label: resources.en["lang.name"] },
      { code: "sw" as LanguageCode, label: resources.sw["lang.name"] },
      { code: "ha" as LanguageCode, label: resources.ha["lang.name"] },
      { code: "yo" as LanguageCode, label: resources.yo["lang.name"] },
      { code: "ar" as LanguageCode, label: resources.ar["lang.name"] },
      { code: "ru" as LanguageCode, label: resources.ru["lang.name"] },
      { code: "zh" as LanguageCode, label: resources.zh["lang.name"] },
      { code: "de" as LanguageCode, label: resources.de["lang.name"] }
    ]
  ), []);

  const value = useMemo<I18nContextValue>(() => ({ lang, setLang, t, available }), [lang, setLang, t, available]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};


